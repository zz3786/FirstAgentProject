package org.example.workflow.core.retry.model;

/**
 * 退避策略
 * <p>
 * 决定"两次重试之间等多久"。
 */
public enum RetryPolicy {

    /**
     * 固定间隔
     * <p>
     * 每次重试都等相同时间。
     * 例：等 200ms、200ms、200ms...
     */
    FIXED,

    /**
     * 指数退避
     * <p>
     * 每次等待时间翻倍。
     * 例：等 200ms、400ms、800ms、1600ms...
     * <p>
     * 适合"依赖方临时过载"——给它更多时间恢复。
     */
    EXPONENTIAL,

    /**
     * 指数退避 + 随机抖动
     * <p>
     * 指数退避基础上加 0~50% 随机量。
     * 例：等 217ms、380ms、832ms...
     * <p>
     * <b>为什么需要抖动</b>：
     * 1000 个客户端同时重试、间隔相同 → 依赖方在每一波重试时被打爆（惊群）。
     * 抖动让每个客户端的重试时间错开。
     */
    EXPONENTIAL_JITTER,

    /**
     * 不等待——立即重试
     * <p>
     * 仅用于"非常快的失败"场景（比如本地锁冲突）。
     * <p>
     * 注意：间隔 0 会让重试风暴，慎用。
     */
    IMMEDIATE
}